"""Builds reports/results.json (what the dashboard reads), reports/RESULTS.md and the README block from the
experiment files. Nothing in those three is written by hand."""

from __future__ import annotations

import json
from datetime import UTC, datetime

from qloop.config import ROOT, Settings

START, END = "<!-- results:start -->", "<!-- results:end -->"


LABEL = {
    "naive judge": "scored by the naive judge",
    "trusted scorer": "scored by the calibrated judge and checks",
    "small model only": "small model only, calibrated judge and checks",
}


def audit_text(s: dict) -> str:
    a = s["audit"]
    gain, human = a["fitness_gain"], a["human_diff"]
    if a["flagged"]:
        moved = f"fell {-human['estimate']:.0%}" if human["estimate"] < 0 else f"rose only {human['estimate']:.0%}"
        return (
            f"fitness rose {gain:.0%} while experts' pass rate on the audit set {moved} "
            f"(bounds {human['low']:+.0%} to {human['high']:+.0%}): **flagged** as fitting the judge "
            f"({a['labels']} expert labels)"
        )
    return (
        f"fitness rose {gain:.0%}; experts confirm {human['estimate']:+.0%} (bounds {human['low']:+.0%} to "
        f"{human['high']:+.0%}; {a['labels']} expert labels)"
    )


def _pct(x: float) -> str:
    return f"{x * 100:.0f}%"


def _ci(d: dict) -> str:
    return f"{_pct(d['estimate'])} ({_pct(d['low'])}–{_pct(d['high'])})"


def build(settings: Settings) -> dict:
    reports = ROOT / "reports"
    dev = json.loads((reports / "development.json").read_text())
    held = json.loads((reports / "heldout.json").read_text()) if (reports / "heldout.json").exists() else None
    runs = (
        (reports / "heldout-runs.log").read_text().strip().splitlines()
        if (reports / "heldout-runs.log").exists()
        else []
    )
    results = {
        "generated_at": datetime.now(UTC).isoformat(),
        "heldout_runs": len(runs),
        "development": dev,
        "heldout": held,
        "headline": headline(dev, held),
    }
    (reports / "results.json").write_text(json.dumps(results, indent=1, ensure_ascii=False) + "\n")
    block = readme_block(results)
    (reports / "RESULTS.md").write_text(
        "# Results\n\nGenerated by `qloop report`. Do not edit.\n\n" + block + details(results)
    )
    readme = ROOT / "README.md"
    if readme.exists():
        text = readme.read_text()
        i, j = text.index(START), text.index(END)
        readme.write_text(text[: i + len(START)] + "\n" + block + text[j:])
    return results


def _cfg(rows: list[dict], prefix: str) -> dict:
    return next(r for r in rows if r["name"].startswith(prefix))


def headline(dev: dict, held: dict | None) -> dict:
    cal = dev["calibration"]
    rep = {r["name"]: r for r in cal["reports"]}
    naive_s = next(s for s in dev["searches"] if s["name"] == "naive judge")
    out = {
        "judge_kappa_selected": rep[cal["selected"]]["kappa"] if cal["selected"] else None,
        "judge_kappa_naive": rep["judge-small/v1"]["kappa"],
        "humans_kappa": cal["humans"]["kappa"],
        "naive_search_flagged": naive_s["audit"]["flagged"],
        "labels_eur": dev["labels"]["spent_eur"],
    }
    if held:
        rows = held["configs"]
        base, naive = _cfg(rows, "baseline"), _cfg(rows, "best: naive")
        trusted, small = _cfg(rows, "best: trusted"), _cfg(rows, "best: small")
        out.update(
            {
                "baseline_expert": base["expert_pass"]["estimate"],
                "baseline_cost": base["cost_per_1k_eur"],
                "naive_expert": naive["expert_pass"]["estimate"],
                "naive_judge_score": naive["naive_judge_pass"],
                "trusted_expert": trusted["expert_pass"]["estimate"],
                "trusted_cost": trusted["cost_per_1k_eur"],
                "small_expert": small["expert_pass"]["estimate"],
                "small_cost": small["cost_per_1k_eur"],
                "gate_right": sum(1 for r in rows if r["gate_right"] is True),
                "gate_decisions": sum(1 for r in rows if r["gate"] is not None),
            }
        )
    return out


def readme_block(results: dict) -> str:
    dev, held, h = results["development"], results["heldout"], results["headline"]
    cal = dev["calibration"]
    lines = ["Generated by `qloop develop && qloop heldout && qloop report` from the files in `reports/`.", ""]
    if held:
        lines += [
            "| On the held-out set (120 tasks, topics never tuned on) | Expert pass rate | Naive judge says | Cost per 1,000 queries |",
            "|---|---|---|---|",
        ]
        for r in held["configs"]:
            lines.append(
                f"| {r['name']} | {_ci(r['expert_pass'])} | {_pct(r['naive_judge_pass'])} | €{r['cost_per_1k_eur']:.2f} |"
            )
        lines.append("")
    rep = {r["name"]: r for r in cal["reports"]}
    lines.append(
        f"- **Judges calibrated on {cal['n']} expert-labelled answers** (€{cal['spent_eur']:.0f} of expert time): "
        f"`{cal['selected']}` agrees with experts at κ = {rep[cal['selected']]['kappa']:.2f} (two experts agree at κ = "
        f"{cal['humans']['kappa']:.2f}); the cheap holistic judge `judge-small/v1` at κ = {rep['judge-small/v1']['kappa']:.2f}."
    )
    for s in dev["searches"]:
        lines.append(f"- **Search, {LABEL[s['name']]}**: {audit_text(s)}.")
    if held:
        lines.append(
            f"- **Gate** decisions on held-out candidates that experts' paired bounds confirm: {h['gate_right']} of {h['gate_decisions']}. "
            f"Held-out set run {results['heldout_runs']} time(s), pin `{held['pin'][:12]}`."
        )
    rt = dev["redteam"]
    lines.append(
        f"- **Injection guard**: {rt['development']['caught']}/{rt['development']['attacks']} known attacks caught, "
        f"{len(rt['development']['false_positives'])} false positives on {rt['development']['benign']} benign clauses; "
        f"**{rt['heldout']['caught']}/{rt['heldout']['attacks']} of attacks written after it was built**, which is why "
        f"the prompt defence and the output check exist."
    )
    return "\n".join(lines) + "\n"


def details(results: dict) -> str:
    dev, held = results["development"], results["heldout"]
    out = [
        "",
        "## Judge calibration",
        "",
        "| Judge | κ vs experts | Agreement | Judge pass | Expert pass | Passed what experts failed | Long-answer bias |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in dev["calibration"]["reports"]:
        out.append(
            f"| {r['name']} | {r['kappa']:.2f} | {_pct(r['agreement'])} | {_pct(r['judge_pass'])} | {_pct(r['human_pass'])} | {r['false_pass']} | {r['long_bias']:+.2f} |"
        )
    out += [
        "",
        "## Searches (development set)",
        "",
        "| Search | Best config | Validation expert pass | Cost per 1k | Rollouts | Audit |",
        "|---|---|---|---|---|---|",
    ]
    for s in dev["searches"]:
        diff = {k: v for k, v in s["best"].items() if s["start"].get(k) != v}
        out.append(
            f"| {s['name']} | {diff} | {_pct(s['val_expert']['start'])} → {_pct(s['val_expert']['best'])} | "
            f"€{s['cost_per_1k']['start']:.2f} → €{s['cost_per_1k']['best']:.2f} | {s['rollouts']} | {audit_text(s)} |"
        )
    out += [
        "",
        f"Configs the validation set cannot tell apart (paired bootstrap, {dev['ranking']['validation_items']} items): "
        + " / ".join(", ".join(g) for g in dev["ranking"]["groups"]),
        "",
    ]
    if held:
        out += [
            "## Held-out gate decisions",
            "",
            "| Candidate | Verdict | Reasons | Experts' paired difference | Gate right |",
            "|---|---|---|---|---|",
        ]
        for r in held["configs"]:
            if r["gate"]:
                d = r["expert_diff_vs_baseline"]
                out.append(
                    f"| {r['name']} | {r['gate']['verdict']} | {'; '.join(r['gate']['reasons'])} | {d['estimate']:+.1%} ({d['low']:+.1%} to {d['high']:+.1%}) | {r['gate_right']} |"
                )
        out += [
            "",
            "## Prompt injection (held-out discovery documents)",
            "",
            "| Defence | Documents | Obeyed | Caught by output check |",
            "|---|---|---|---|",
        ]
        for r in held["injection"]:
            out.append(f"| {r['defence']} | {r['n']} | {r['obeyed']} | {r['caught_by_output_check']} |")
        out += [
            "",
            f"Traces: {held['traces']['events']} Langfuse events for the held-out baseline, {held['traces']['raw_secrets_found']} raw client names, emails or IBANs in them.",
        ]
    return "\n".join(out) + "\n"
